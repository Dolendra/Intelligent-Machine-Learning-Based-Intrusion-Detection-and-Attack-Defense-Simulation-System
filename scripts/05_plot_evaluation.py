"""Generate report figures: confusion matrices, ROC, feature importances."""
from __future__ import annotations

import json
import sys
from pathlib import Path

import matplotlib.pyplot as plt
import numpy as np
import seaborn as sns
from sklearn.metrics import ConfusionMatrixDisplay, RocCurveDisplay, roc_curve, auc

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

from ids_config import load_config, resolve_path
from ml.features.pipeline import FeatureBundle, transform_split
from ml.models.factory import load_model
from ml.preprocessing.dataset import load_processed


def main() -> None:
    cfg = load_config()
    model_dir = resolve_path(cfg["models"]["output_dir"])
    out = model_dir / "figures"
    out.mkdir(parents=True, exist_ok=True)

    bundle = FeatureBundle.load(model_dir / "feature_bundle.joblib")
    binary = load_model(model_dir / "binary_best.joblib")
    multi = load_model(model_dir / "multiclass_best.joblib")
    test = load_processed("test")
    # Subsample for plotting speed if huge
    if len(test) > 80000:
        test = test.sample(80000, random_state=cfg["data"]["random_state"])
    X, y_bin, y_multi = transform_split(bundle, test)

    # Binary confusion matrix
    y_pred = binary.predict(X)
    fig, ax = plt.subplots(figsize=(5, 4))
    ConfusionMatrixDisplay.from_predictions(y_bin, y_pred, display_labels=["Benign", "Attack"], ax=ax, cmap="Blues")
    ax.set_title("Binary confusion matrix (test sample)")
    fig.tight_layout()
    fig.savefig(out / "binary_confusion_matrix.png", dpi=160)
    plt.close(fig)

    # ROC
    if hasattr(binary, "predict_proba"):
        scores = binary.predict_proba(X)[:, 1]
        fpr, tpr, _ = roc_curve(y_bin, scores)
        fig, ax = plt.subplots(figsize=(5, 4))
        ax.plot(fpr, tpr, color="#3ec7c2", lw=2, label=f"AUC = {auc(fpr, tpr):.4f}")
        ax.plot([0, 1], [0, 1], "--", color="#8fa6b5")
        ax.set_xlabel("False positive rate")
        ax.set_ylabel("True positive rate")
        ax.set_title("Binary ROC (test sample)")
        ax.legend(loc="lower right")
        fig.tight_layout()
        fig.savefig(out / "binary_roc.png", dpi=160)
        plt.close(fig)

    # Multiclass confusion matrix
    y_mpred = multi.predict(X)
    labels = list(bundle.label_encoder.classes_)
    fig, ax = plt.subplots(figsize=(8, 6))
    ConfusionMatrixDisplay.from_predictions(
        y_multi,
        y_mpred,
        display_labels=labels,
        ax=ax,
        cmap="Greens",
        xticks_rotation=45,
        colorbar=True,
    )
    ax.set_title("Multiclass confusion matrix (test sample)")
    fig.tight_layout()
    fig.savefig(out / "multiclass_confusion_matrix.png", dpi=160)
    plt.close(fig)

    # Feature importance (tree models)
    names = bundle.selected_features
    if hasattr(binary, "feature_importances_"):
        imp = binary.feature_importances_
    elif hasattr(multi, "feature_importances_"):
        imp = multi.feature_importances_
    else:
        imp = np.abs(getattr(binary, "coef_", [np.zeros(len(names))])[0])
        if getattr(imp, "ndim", 1) > 1:
            imp = np.mean(np.abs(imp), axis=0)
    order = np.argsort(imp)[::-1][:15]
    fig, ax = plt.subplots(figsize=(8, 5))
    sns.barplot(x=imp[order], y=np.array(names)[order], ax=ax, color="#e4a54a")
    ax.set_title("Top 15 features (model importance)")
    ax.set_xlabel("Importance")
    fig.tight_layout()
    fig.savefig(out / "feature_importance.png", dpi=160)
    plt.close(fig)

    # Copy metrics summary beside figures
    report = json.loads((model_dir / "training_report.json").read_text(encoding="utf-8"))
    (out / "README.md").write_text(
        "\n".join(
            [
                "# Evaluation figures",
                "",
                f"- Best binary: `{report['binary']['best']}`",
                f"- Best multiclass: `{report['multiclass']['best']}`",
                f"- Binary test F1: {report['binary']['test']['f1']:.4f}",
                f"- Multiclass weighted F1: {report['multiclass']['test']['f1_weighted']:.4f}",
                "",
                "Generated by `scripts/05_plot_evaluation.py`.",
                "",
            ]
        ),
        encoding="utf-8",
    )
    print(f"Wrote figures to {out}")
    for p in sorted(out.glob("*.png")):
        print(" -", p.name)


if __name__ == "__main__":
    main()
